import assert from 'node:assert/strict';
import {VoiceRelay, RELAY_WAIT_MS, VOICE_RELAY_WAIT_MS} from './src/index.mjs';
assert.equal(RELAY_WAIT_MS, 28000, 'MCP deadline unchanged');
assert.equal(VOICE_RELAY_WAIT_MS, 35000, '30s useful work plus5s transport receipt reserve');
const realSetTimeout = globalThis.setTimeout, realClearTimeout = globalThis.clearTimeout;
let now = 0, seq = 0;
const timers = new Map();
globalThis.setTimeout = (fn, ms) => {const id = ++seq;timers.set(id,{fn,due:now+ms,ms});return id;};
globalThis.clearTimeout = id => timers.delete(id);
const advance = ms => {now+=ms;for(const [id,t] of timers)if(t.due<=now){timers.delete(id);t.fn();}};
const token = 'local-authenticated-voice-test-token';
const ws = {sent:[],deserializeAttachment:() => ({authenticated:true,authAt:1}),send(message){this.sent.push(JSON.parse(message));}};
const relay = new VoiceRelay({getWebSockets:() => [ws]}, {OWNER_TOKEN:token});
const request = (id) => new Request('https://relay.example/voice',{method:'POST',headers:{authorization:'Bearer '+token,'content-type':'application/json'},body:JSON.stringify({requestId:id,request:'Lis mes factures sans payer.'})});
try {
  const waiting = relay.handleVoice(request('voice-at-29s'));
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(timers.size,1);assert.equal([...timers.values()][0].ms,35000);
  advance(29000);
  assert(relay.pending.has('voice-at-29s'),'28–30s answer still awaited');
  const receipt = {success:true,state:'done',source:'samantha_brain',text:'Réponse du cerveau.',conversationId:'brain-test'};
  await relay.webSocketMessage(ws,JSON.stringify({type:'response',requestId:'voice-at-29s',response:receipt}));
  assert.deepEqual(await (await waiting).json(),receipt);
  assert.equal(timers.size,0);
  const sent = ws.sent.length;
  assert.deepEqual(await (await relay.handleVoice(request('voice-at-29s'))).json(),receipt);
  assert.equal(ws.sent.length,sent,'same identity reads cached receipt without redispatch');
  const deferred = relay.handleVoice(request('voice-deferred-30s'));
  await new Promise(resolve => setImmediate(resolve));
  advance(30000);
  const unknown={success:false,state:'unknown',source:'samantha_brain',error:'voice_brain_budget_exhausted',retrySafe:false,conversationId:'brain-deferred'};
  await relay.webSocketMessage(ws,JSON.stringify({type:'response',requestId:'voice-deferred-30s',response:unknown}));
  const response=await deferred;
  assert.equal(response.status,502);assert.deepEqual(await response.json(),unknown);
  const sentAfterUnknown=ws.sent.length;
  assert.deepEqual(await (await relay.handleVoice(request('voice-deferred-30s'))).json(),unknown);
  assert.equal(ws.sent.length,sentAfterUnknown,'uncertain effect is never replayed');
  const disconnected=relay.handleVoice(request('voice-disconnected'));
  await new Promise(resolve => setImmediate(resolve));
  await relay.webSocketClose();
  const disconnectedResult=await (await disconnected).json();
  assert.equal(disconnectedResult.error,'device_disconnected');assert.equal(disconnectedResult.state,'unknown');assert.equal(disconnectedResult.retrySafe,false);
} finally {globalThis.setTimeout=realSetTimeout;globalThis.clearTimeout=realClearTimeout;}
console.log('voice-brain-budget: PASS (MCP28 unchanged, real receipt at29/30s,35s transport-only reserve, no uncertain replay; virtual time)');
